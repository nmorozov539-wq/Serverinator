#!/usr/bin/env bash
# Tests --add-client / --revoke-client: distinct per-client keys, delivered
# over the live VPS->phone channel (mocked here as a local "phone_home"
# sandbox instead of a real SSH connection), plus the default-mode change
# (initial setup always mints a fresh owner key rather than reusing whatever
# is already in the VPS owner's authorized_keys).
set -uo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

devroot="$tmp/vps"
phone_home="$tmp/phone_home"
mkdir -p "$phone_home"

cat > "$tmp/handoff.json" <<EOF
{
  "version": 1,
  "device_name": "rn9p",
  "wg_pubkey": "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=",
  "wstunnel_port": 9443,
  "wg_port": 51822,
  "ssh_enabled": 1,
  "ssh_user": "root",
  "ssh_port": 2222,
  "ssh_host_fingerprint": "SHA256:TEST"
}
EOF

echo "Test: validate_client_label"
for bad in 'Bad Label' 'a;rm -rf' '' "$(printf 'a%.0s' {1..33})"; do
    rc=0; (source "$VPS_SCRIPT" >/dev/null 2>&1; validate_client_label "$bad") >/dev/null 2>&1 || rc=$?
    assert_eq 1 "$rc" "rejects invalid label '${bad:0:20}'"
done
rc=0; (source "$VPS_SCRIPT" >/dev/null 2>&1; validate_client_label "laptop-2") >/dev/null 2>&1 || rc=$?
assert_eq 0 "$rc" 'accepts a normal label'

echo "Test: initial setup always mints a fresh owner key (no auto-detect)"
rc=0
SERVERINATOR_DEV=1 SERVERINATOR_DEV_ROOT="$devroot" SERVERINATOR_VPS_IP=203.0.113.9 \
    bash -c 'source "$1"; main "$2" --vps-ip 203.0.113.9' \
    _ "$VPS_SCRIPT" "$tmp/handoff.json" > "$tmp/setup.log" 2>&1 || rc=$?
assert_eq 0 "$rc" "initial setup succeeds"

key_dir="$devroot/etc/wireguard/serverinator/ssh"
assert_file_exists "$key_dir/owner_rn9p" "owner key generated by default"
assert_file_exists "$key_dir/owner_rn9p.pub" "owner pubkey generated by default"
assert_file_exists "$devroot/etc/wireguard/serverinator/devices/rn9p.json" "device record persisted for add-client/revoke-client"
assert_contains "$(cat "$key_dir/client-setup-owner-rn9p.sh")" 'KEY="$HOME/.ssh/si-rn9p"' \
    "owner client-setup embeds a fresh identity by default"
assert_eq "rn9p" "$(jq -r .device_name "$devroot/etc/wireguard/serverinator/devices/rn9p.json")" "device record carries device_name"

echo "Test: add-client without a prior install fails cleanly"
rc=0
SERVERINATOR_DEV=1 SERVERINATOR_DEV_ROOT="$tmp/never-installed" \
    bash -c 'source "$1"; CLIENT_LABEL=x; add_client' \
    _ "$VPS_SCRIPT" > "$tmp/noinstall.log" 2>&1 || rc=$?
assert_eq 1 "$rc" 'add_client fails without a prior install'
assert_contains "$(cat "$tmp/noinstall.log")" "No phone is set up on this VPS" 'reports the missing state'

echo "Test: --add-client creates a distinct key and delivers it to the phone"
rc=0
SERVERINATOR_DEV=1 SERVERINATOR_DEV_ROOT="$devroot" \
    bash -c '
        source "$1"
        ssh() { local cmd="${!#}"; HOME="'"$phone_home"'" bash -c "$cmd"; }
        main --add-client laptop --generate-key
    ' _ "$VPS_SCRIPT" > "$tmp/add1.log" 2>&1 || rc=$?
assert_eq 0 "$rc" "add_client succeeds"
assert_file_exists "$key_dir/owner_rn9p_laptop" "distinct client key created"
assert_file_exists "$key_dir/owner_rn9p_laptop.pub" "distinct client pubkey created"
setup_script="$key_dir/client-setup-laptop-rn9p.sh"
assert_file_exists "$setup_script" "client-setup script generated for laptop"
assert_contains "$(cat "$setup_script")" "Host serverinated-laptop" "distinct alias per client"
assert_contains "$(cat "$setup_script")" 'KEY="$HOME/.ssh/si-rn9p-laptop"' "distinct identity filename per client"
assert_contains "$(cat "$setup_script")" "Host serverinated-laptop-jump" "a jump block of its own"
assert_contains "$(cat "$setup_script")" 'HostName 203.0.113.9' "the jump goes to the VPS"
laptop_pub="$(cat "$key_dir/owner_rn9p_laptop.pub")"
assert_contains "$(cat "$phone_home/.ssh/authorized_keys")" "$laptop_pub" "laptop key delivered to phone authorized_keys"

admin_authorized_keys="$devroot/root/.ssh/authorized_keys"
assert_file_exists "$admin_authorized_keys" "VPS admin authorized_keys created for jump access"
assert_contains "$(cat "$admin_authorized_keys")" "restrict,port-forwarding,permitopen=\"${TEST_PHONE_IP}:2222\" $laptop_pub" \
    "laptop's VPS jump entry is restricted to port-forwarding to the phone only"

echo "Test: --add-client refuses to clobber an existing label"
rc=0
SERVERINATOR_DEV=1 SERVERINATOR_DEV_ROOT="$devroot" \
    bash -c '
        source "$1"
        ssh() { local cmd="${!#}"; HOME="'"$phone_home"'" bash -c "$cmd"; }
        main --add-client laptop --generate-key
    ' _ "$VPS_SCRIPT" > "$tmp/add1-dup.log" 2>&1 || rc=$?
assert_eq 1 "$rc" 'duplicate label rejected'
dup_count="$(grep -cF "$laptop_pub" "$phone_home/.ssh/authorized_keys")"
assert_eq 1 "$dup_count" 'rejected duplicate did not touch the phone'

echo "Test: a second, independent client can be added"
rc=0
SERVERINATOR_DEV=1 SERVERINATOR_DEV_ROOT="$devroot" \
    bash -c '
        source "$1"
        ssh() { local cmd="${!#}"; HOME="'"$phone_home"'" bash -c "$cmd"; }
        main --add-client friend --generate-key
    ' _ "$VPS_SCRIPT" > "$tmp/add2.log" 2>&1 || rc=$?
assert_eq 0 "$rc" "second client add succeeds"
friend_pub="$(cat "$key_dir/owner_rn9p_friend.pub")"
assert_contains "$(cat "$phone_home/.ssh/authorized_keys")" "$friend_pub" "friend key also delivered"
[[ "$laptop_pub" != "$friend_pub" ]] && pass "laptop and friend got distinct keys" || failtest "keys collided"

echo "Test: --revoke-client removes only the targeted client"
rc=0
SERVERINATOR_DEV=1 SERVERINATOR_DEV_ROOT="$devroot" \
    bash -c '
        source "$1"
        ssh() { local cmd="${!#}"; HOME="'"$phone_home"'" bash -c "$cmd"; }
        main --revoke-client laptop
    ' _ "$VPS_SCRIPT" > "$tmp/revoke1.log" 2>&1 || rc=$?
assert_eq 0 "$rc" "revoke_client succeeds"
assert_file_missing "$key_dir/owner_rn9p_laptop" "local client key removed"
assert_file_missing "$key_dir/owner_rn9p_laptop.pub" "local client pubkey removed"
assert_file_missing "$setup_script" "client-setup script removed"
assert_not_contains "$(cat "$phone_home/.ssh/authorized_keys")" "$laptop_pub" "laptop key removed from phone"
assert_contains "$(cat "$phone_home/.ssh/authorized_keys")" "$friend_pub" "friend key untouched by laptop's revocation"
assert_not_contains "$(cat "$admin_authorized_keys")" "$laptop_pub" "laptop's VPS jump entry removed"
friend_vps_entry="restrict,port-forwarding,permitopen=\"${TEST_PHONE_IP}:2222\" $friend_pub"
assert_contains "$(cat "$admin_authorized_keys")" "$friend_vps_entry" "friend's VPS jump entry untouched by laptop's revocation"

echo "Test: revoking an already-revoked or unknown client fails cleanly"
rc=0
SERVERINATOR_DEV=1 SERVERINATOR_DEV_ROOT="$devroot" \
    bash -c '
        source "$1"
        ssh() { local cmd="${!#}"; HOME="'"$phone_home"'" bash -c "$cmd"; }
        main --revoke-client laptop
    ' _ "$VPS_SCRIPT" > "$tmp/revoke2.log" 2>&1 || rc=$?
assert_eq 1 "$rc" 're-revoking an already-revoked client fails'
rc=0
SERVERINATOR_DEV=1 SERVERINATOR_DEV_ROOT="$devroot" \
    bash -c '
        source "$1"
        ssh() { local cmd="${!#}"; HOME="'"$phone_home"'" bash -c "$cmd"; }
        main --revoke-client neverexisted
    ' _ "$VPS_SCRIPT" > "$tmp/revoke3.log" 2>&1 || rc=$?
assert_eq 1 "$rc" 'revoking an unknown client fails'

exit "$TESTS_FAILED"
